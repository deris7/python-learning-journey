#Demonstrate  a while loop, counting down
i = 3
while i != 0:
    print('meow')
    i = i - 1 
#Demonstrate  a while loop, counting up from 1
i = 1
while i <= 3:
    print('meow')
    i = i + 1
#Demonstrate  a while loop, counting up from 0
i = 0
while i < 3:
    print('meow')
    i = i + 1
#Demonstrate (more succinct) incrementation
i = 0
while i < 3:
    print('meow')
    i += 1
