#Integer
my_int = 10
print("integer :", my_int)

#float - a number with decimal point
my_float = 4.50
print("float :", my_float)

#string - sequence character enclosed in single or double quotation marks
my_string = "Hello"
print("String :", my_string)

#boolean - true or false type
my_boolean = True
print("Boolean :", my_boolean)

#to see what type variable is, we can use type() function
print(type(my_string))
print(type(my_float))
print(type(my_int))